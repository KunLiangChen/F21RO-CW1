"""
Visualization Script for Task 3 Training and Hyperparameter Tuning.

This script reads training log JSON files generated by 'train_ann.py' from 'logs/' directory
and produces high-resolution vector/raster figures in 'plots/' directory for use in:
    1. A0 Poster Deliverable (Task 5)
    2. Video Presentation Slides (Task 5)

Generated Figures:
    - loss_curves.png: Epoch-wise loss convergence comparison across Small, Medium, and Large models.
    - val_error_comparison.png: Validation MSE & MAE performance comparison across dataset scales.

Coursework Reference:
    F20/21RO Intelligent Robotics - Coursework 1 Task 3 & Task 5
"""

import os
import json
import matplotlib.pyplot as plt
import numpy as np

# Set project root and directories
PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))
LOGS_DIR = os.path.join(PROJECT_ROOT, "logs")
PLOTS_DIR = os.path.join(PROJECT_ROOT, "plots")

# Configure Matplotlib styling for academic publication/poster quality
plt.style.use('seaborn-v0_8-whitegrid' if 'seaborn-v0_8-whitegrid' in plt.style.available else 'default')
plt.rcParams['font.sans-serif'] = ['DejaVu Sans', 'Arial', 'Helvetica']
plt.rcParams['axes.edgecolor'] = '#cccccc'
plt.rcParams['axes.linewidth'] = 1.0


def load_training_logs():
    """
    Loads JSON logs for Small, Medium, and Large models from the logs directory.

    Returns:
        dict: Scale keys mapped to parsed JSON log dictionaries.
    """
    scales = ["small", "medium", "large"]
    logs_data = {}

    for scale in scales:
        log_path = os.path.join(LOGS_DIR, f"log_{scale}.json")
        if not os.path.exists(log_path):
            print(f"[Warning] Log file for scale '{scale}' not found at: {log_path}")
            continue
        with open(log_path, 'r', encoding='utf-8') as f:
            logs_data[scale] = json.load(f)

    if not logs_data:
        raise FileNotFoundError(
            "No training log files found in 'logs/'! Please run 'python train_ann.py' first."
        )

    return logs_data


def plot_loss_curves(logs_data):
    """
    Plots training Loss (MSE) convergence curves across iterations for Small, Medium, and Large models.
    Saved to 'plots/loss_curves.png'.
    """
    plt.figure(figsize=(9, 5), dpi=300)

    colors = {'small': '#e74c3c', 'medium': '#f39c12', 'large': '#2ecc71'}
    line_styles = {'small': '--', 'medium': '-.', 'large': '-'}

    for scale, log in logs_data.items():
        loss_curve = log.get("loss_curve", [])
        if not loss_curve:
            continue
        epochs = np.arange(1, len(loss_curve) + 1)
        best_params = log.get("best_hyperparameters", {})
        hidden_layers = str(best_params.get("hidden_layer_sizes", ""))
        
        plt.plot(
            epochs,
            loss_curve,
            label=f"{scale.capitalize()} Model {hidden_layers}",
            color=colors.get(scale, '#3498db'),
            linestyle=line_styles.get(scale, '-'),
            linewidth=2.0
        )

    plt.yscale('log')  # Logarithmic scale for clear visualization of initial rapid drop and convergence
    plt.title("Training Loss (MSE) Convergence Across Model Scales", fontsize=14, fontweight='bold', pad=12)
    plt.xlabel("Training Iterations (Epochs)", fontsize=12, labelpad=8)
    plt.ylabel("Loss (MSE, Log Scale)", fontsize=12, labelpad=8)
    plt.grid(True, which="both", linestyle=":", alpha=0.6)
    plt.legend(fontsize=11, frameon=True, facecolor='white', framealpha=0.9)
    plt.tight_layout()

    output_path = os.path.join(PLOTS_DIR, "loss_curves.png")
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"[Saved] Loss convergence plot saved to: {os.path.relpath(output_path, PROJECT_ROOT)}")


def plot_validation_metrics(logs_data):
    """
    Plots bar chart comparisons of Validation MSE and MAE across Small, Medium, and Large models.
    Saved to 'plots/val_error_comparison.png'.
    """
    scales = [s for s in ["small", "medium", "large"] if s in logs_data]
    mses = [logs_data[s]["validation_metrics"]["mse"] for s in scales]
    maes = [logs_data[s]["validation_metrics"]["mae"] for s in scales]

    x = np.arange(len(scales))
    width = 0.35

    fig, ax1 = plt.subplots(figsize=(8, 5), dpi=300)

    # MSE Bars (Left Y-Axis)
    rects1 = ax1.bar(x - width/2, mses, width, label='Validation MSE', color='#3498db', alpha=0.85)
    ax1.set_xlabel('Model Scale / Dataset Size', fontsize=12, labelpad=8)
    ax1.set_ylabel('Mean Squared Error (MSE)', fontsize=12, color='#2980b9')
    ax1.tick_params(axis='y', labelcolor='#2980b9')
    ax1.set_xticks(x)
    ax1.set_xticklabels([s.capitalize() for s in scales], fontsize=11, fontweight='bold')

    # MAE Bars (Right Y-Axis)
    ax2 = ax1.twinx()
    rects2 = ax2.bar(x + width/2, maes, width, label='Validation MAE', color='#e67e22', alpha=0.85)
    ax2.set_ylabel('Mean Absolute Error (MAE)', fontsize=12, color='#d35400')
    ax2.tick_params(axis='y', labelcolor='#d35400')

    # Add numeric value labels on top of bars
    def autolabel(rects, ax, fmt="{:.2e}"):
        for rect in rects:
            height = rect.get_height()
            ax.annotate(
                fmt.format(height),
                xy=(rect.get_x() + rect.get_width() / 2, height),
                xytext=(0, 3),  # 3 points vertical offset
                textcoords="offset points",
                ha='center', va='bottom', fontsize=9
            )

    autolabel(rects1, ax1, fmt="{:.2e}")
    autolabel(rects2, ax2, fmt="{:.4f}")

    plt.title("Validation Set Error Comparison Across Model Scales", fontsize=14, fontweight='bold', pad=12)
    fig.tight_layout()

    output_path = os.path.join(PLOTS_DIR, "val_error_comparison.png")
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"[Saved] Validation metrics comparison plot saved to: {os.path.relpath(output_path, PROJECT_ROOT)}")


def main():
    """
    Main visualization workflow loading logs and generating figures.
    """
    os.makedirs(PLOTS_DIR, exist_ok=True)
    print("\n========================================================")
    print("  Generating Task 3 Training & Tuning Visualizations")
    print("========================================================\n")

    logs_data = load_training_logs()
    plot_loss_curves(logs_data)
    plot_validation_metrics(logs_data)

    print("\n========================================================")
    print("  All Plots Generated Successfully in 'plots/' Directory!")
    print("========================================================\n")


if __name__ == "__main__":
    main()